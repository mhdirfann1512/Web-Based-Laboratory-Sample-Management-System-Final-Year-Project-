const fs = require("fs")
const path = require("path")

const filePath = path.join(__dirname, "..", "public", "html", "register-sample.html")

try {
  let content = fs.readFileSync(filePath, "utf8")

  // Find and remove any JavaScript code that's appearing as visible text
  // This removes any stray JavaScript that escaped from script tags
  content = content.replace(
    /'; printWindow\.document\.write$$labelHtml$$; printWindow\.document\.close$$$$; \} function registerAnother$$$$ \{ document\.getElementById$$'successDisplay'$$\.style\.display = 'none'; document\.getElementById$$'sampleRegistrationForm'$$\.reset$$$$; clearAutoGeneratedFields$$$$; document\.getElementById$$'testType'$$\.disabled = true; document\.getElementById$$'storageLocation'$$\.disabled = true; document\.getElementById$$'collectionDate'$$\.value = new Date$$$$\.toISOString$$$$\.split$$'T'$$\[0\]; \} function viewAllSamples$$$$ \{ window\.location\.href = '\/view-samples'; \}/g,
    "",
  )

  // Also remove any other stray JavaScript patterns
  content = content.replace(
    /printWindow\.document\.write$$htmlContent$$; printWindow\.document\.close$$$$; \} function registerAnother$$$$ \{[^<]*/g,
    "",
  )

  // Remove any loose JavaScript function definitions that might be visible
  content = content.replace(/\} function registerAnother$$$$ \{[^<]*$/g, "")
  content = content.replace(/function viewAllSamples$$$$ \{[^<]*$/g, "")

  // Clean up any trailing JavaScript code at the end
  content = content.replace(/'; printWindow[^<]*$/g, "")
  content = content.replace(/printWindow[^<]*$/g, "")

  // Ensure the HTML ends properly
  if (!content.trim().endsWith("</html>")) {
    // Find the last proper closing tag and ensure it ends with </html>
    const lastScriptIndex = content.lastIndexOf("</script>")
    if (lastScriptIndex !== -1) {
      content = content.substring(0, lastScriptIndex + 9) + "\n</body>\n</html>"
    }
  }

  fs.writeFileSync(filePath, content)
  console.log("✅ Successfully removed visible JavaScript code from register-sample.html")
  console.log("🚀 The page should now be clean without any visible JavaScript at the bottom!")
} catch (error) {
  console.error("❌ Error fixing the file:", error.message)
}
