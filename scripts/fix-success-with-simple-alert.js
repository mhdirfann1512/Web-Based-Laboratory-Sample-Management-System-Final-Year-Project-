const fs = require("fs")
const path = require("path")

console.log("🔧 Fixing success modal JavaScript error...")

const filePath = path.join(__dirname, "..", "public", "html", "register-sample.html")

try {
  let content = fs.readFileSync(filePath, "utf8")

  // Remove the broken showSuccess function and replace with simple alert
  const newShowSuccessFunction = `
        function showSuccess(result) {
            // Simple alert instead of modal
            alert('Sample registered successfully!');
            
            // Reset the form
            document.getElementById('sampleRegistrationForm').reset();
            clearAutoGeneratedFields();
            document.getElementById('testType').disabled = true;
            document.getElementById('storageLocation').disabled = true;
            document.getElementById('collectionDate').value = new Date().toISOString().split('T')[0];
        }`

  // Find and replace the showSuccess function
  const showSuccessRegex = /function showSuccess\([^}]*\{[^}]*\}/gs
  if (content.match(showSuccessRegex)) {
    content = content.replace(showSuccessRegex, newShowSuccessFunction)
    console.log("✅ Replaced showSuccess function with simple alert")
  } else {
    // If showSuccess function not found, add it before the closing script tag
    const scriptEndRegex = /<\/script>/
    content = content.replace(scriptEndRegex, newShowSuccessFunction + "\n    </script>")
    console.log("✅ Added new showSuccess function with simple alert")
  }

  // Remove the success modal HTML entirely
  const modalRegex = /<div id="successDisplay"[^>]*>.*?<\/div>\s*<\/div>/gs
  content = content.replace(modalRegex, "")
  console.log("✅ Removed success modal HTML")

  // Write the updated content back to the file
  fs.writeFileSync(filePath, content, "utf8")
  console.log("✅ Success modal JavaScript error fixed!")
  console.log("📋 Now registration will show a simple alert instead of the modal")
} catch (error) {
  console.error("❌ Error fixing success modal:", error.message)
}
